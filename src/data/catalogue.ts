export const CATALOGUE_SKILLS: CatalogueSkill[] = Object.entries(ROWS).flatMap(
  ([domain, rows]) =>
    rows.map(([id, level, title, does, gesture, prerequisites, lesson]) => {
      const before = rows.find((row) => row[1] === level - 1);
      return {
        id,
        domain,
        level,
        title,
        does,
        gesture,
        prerequisites:
          prerequisites ?? (before && level > 0 ? [before[0]] : []),
        lesson,
      };
    }),
);

export function domainSkills(domainId: string) {
  return CATALOGUE_SKILLS.filter((skill) => skill.domain === domainId);
}
