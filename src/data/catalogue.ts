/**
 * Le catalogue des compétences (idées 13 et 15 d'Angel) : tous les domaines,
 * du débutant total à l'expert, même les gestes « bêtes » et pratiques.
 *
 * Une compétence = une chose qu'on saura FAIRE, en ≈ 10 minutes : une idée
 * simple, un geste pratique (souvent un vrai modèle à remplir), un petit
 * contrôle. Celles qui ont déjà leur leçon la nomment (`lesson`) ; les autres
 * s'écriront peu à peu. Données pures, sans dépendance.
 */

export type CatalogueLevel = 0 | 1 | 2 | 3;

export const LEVEL_NAMES: Record<CatalogueLevel, string> = {
  0: "Découvrir",
  1: "Savoir faire",
  2: "Maîtriser",
  3: "Expert",
};

export type CatalogueGroup =
  "Ton argent" | "Ton activité" | "Ton travail" | "Le numérique";

export type CatalogueDomain = {
  id: string;
  /** Le nom dit à quoi sert le domaine, en mots de tous les jours. */
  name: string;
  promise: string;
  group: CatalogueGroup;
  /** Domaine des 43 premières leçons (proposé à tous au départ). */
  core?: string;
};

export type CatalogueSkill = {
  id: string;
  domain: string;
  level: CatalogueLevel;
  title: string;
  /** Ce que tu sauras faire, en une phrase. */
  does: string;
  /** Le geste pratique, souvent un modèle à remplir. */
  gesture?: string;
  prerequisites: string[];
  /** La leçon déjà écrite qui couvre cette compétence. */
  lesson?: string;
};

